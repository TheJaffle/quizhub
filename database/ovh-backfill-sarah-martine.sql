SELECT a.id, a.test_id, q.section_id, q.id, a.user_id,
       CASE WHEN b.answer_state = 'correct' AND q.question_format NOT IN ('visual_overlay', 'spatial_overlay') THEN correct.id ELSE NULL END AS selected_option_id,
       CASE
         WHEN b.answer_state = 'correct' AND q.question_format IN ('visual_overlay', 'spatial_overlay') THEN overlay.correct_position
         WHEN b.answer_state = 'correct' AND q.question_format NOT IN ('visual_overlay', 'spatial_overlay') THEN correct.position
         ELSE NULL
       END AS selected_position,
       CASE
         WHEN q.question_format IN ('visual_overlay', 'spatial_overlay') THEN overlay.correct_position
         ELSE correct.position
       END AS correct_position,
       CASE WHEN b.answer_state = 'correct' THEN 1 ELSE 0 END AS is_correct,
       q.difficulty_level,
       q.weight,
       CASE WHEN b.answer_state = 'correct' THEN q.weight ELSE 0 END AS points_earned,
       b.response_time_ms,
       NULL AS displayed_at,
       COALESCE(a.completed_at, NOW()) AS answered_at
FROM tmp_iq_backfill b
JOIN iq_attempts a ON a.attempt_token = b.attempt_token
JOIN iq_tests t ON t.id = a.test_id
JOIN iq_questions q ON q.question_key = b.question_key AND q.test_id = COALESCE(t.question_bank_test_id, a.test_id) AND q.is_active = 1
JOIN iq_sections s ON s.id = q.section_id AND s.is_active = 1
LEFT JOIN iq_question_options correct ON correct.question_id = q.id AND correct.is_correct = 1 AND correct.is_active = 1
LEFT JOIN iq_spatial_overlay_questions overlay ON overlay.question_id = q.id AND overlay.is_active = 1
LEFT JOIN iq_attempt_answers existing ON existing.attempt_id = a.id AND existing.question_id = q.id
WHERE existing.id IS NULL
  AND s.section_key IN ('quantitative', 'memory', 'long_memory', 'audio_memory', 'speed');

